<p align="center"><strong>Posuk on Video</strong></p>
<p>At every rally we have children from around the world saying pesukim. The 12 chosen children say the posuk on video and that video is played at the rally. During the rally, the children repeat the posuk word for word as if the posuk is live.</p>
<p>If your school has been chosen to say the posuk, you will be notified through email.</p>
<p><strong>How to take the video:</strong></p>
<p><strong>Posuk</strong></p>
<ul>
  <li>Choose one child to say the Posuk with lots of Chayus as well as slowly and clearly as ALL Chayolim will be repeating this at the rally.</li>
  <li>Please pronounce Hashem's name when necessary.</li>
  <li>To ensure there will be enough time between each word at the rally, a class of children should be repeating to the Posuk.</li>
</ul>
<p>(The one videoing should not repeat the Posuk.) </p>
<p><strong>Video</strong></p>
<ul>
  <li>The video should be taken in an appropriate location where rallies are usually held i.e. school stage.</li>
  <li>Record 3 seconds of the child waiting quietly to start the posuk. Do the same after the posuk is said.</li>
  <li>Do not include the children repeating the posuk on the video, we should only see the chosen child.</li>
</ul>
<br />
<p><strong>Send</strong></p>
<ul>
  <li>Please send us the video two weeks before the rally the latest!</li>
  <li>Send us the video through <a href="http://yousendit.com/" target="_blank">yousendit.com</a></li>
  <li>Include the name and rank of the child in the email</li>
  <li>If you are unable to take this video and send it in to us on time, let us know ASAP so we can choose another school and give them enough notice.</li>
</ul>
