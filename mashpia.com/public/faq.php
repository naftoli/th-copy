<p><strong><a href="javascript:toggle('a11')"><?=$i++ . ". "; ?>How do the  auctions work?</a></strong><br />
<div id="a11" style="display:none;">
  Chayolei Tzivos Hashem will hold 4 auctions during  the year of 5771.<br />
  &nbsp; <br />
  Chayolim &quot;buy tickets&quot; for a chance to  win a prize. Tickets can be bought for as few as 5 miles!<br />
  The system will let you know how many miles you  have available for the auction. The miles that are available are the miles  earned since the previous auction. </p>
<p>PRIZE CATEGORIES<br />
  Every year children will have access to more  prizes. The following&nbsp;are the prize choices&nbsp;each grade has:</p>
<p>Kindergarten:&nbsp;Five  Point Prizes<br />
  Pre-1-A:&nbsp;Ten  Point Prizes<br />
  First  Grade:&nbsp;Eighteen Point Prizes<br />
  Second  Grade: Fifty-Four Point Prizes<br />
  Third  Grade: One Hundred Point Prizes<br />
  Fourth  Grade: Three Hundred and Sixty Point Prizes<br />
  Fifth  Grade: Seven Hundred Point Prizes<br />
  Sixth and  Seventh&nbsp;Grade: One Thousand Point Prizes</p>
<p>Each auction higher point prizes are made  available. By the last auction of the year, the One Thousand Point Prizes will  be made available for the applicable age group.</p>
<p>EMPTY CARTS<br />
  If you have not chosen prizes, or you have not used  up your miles by the auction date, the computer will randomly buy tickets with  your miles. (On the date of the auction, every Chayols mile balance will be  0.)<br />
  There is no need to enter prize selections for  kindergarten and grades 1&amp; 2, the computer will automatically choose prizes  for them.</p>
<p>GET PREVIOUS MILES BACK!<br />
  If a Chayol has earned at least 150 miles since the  last auction, s/he will be able to reuse all miles since the beginning of the  year.<br />
  If a Chayol has earned at least 1200 miles during  the year, s/he will be able to reuse all previous miles in the final auction of  the year.</p>
<p>The top auction winners are announced at the  following rally. The list of all winners will be sent to the base commanders to  announce in their base. Chayolim will also be able to view the winners on their  kiosk account. </p>
