<p><strong>Registration 5772: </strong>At midnight on Monday, September 12 (Monday night) all children and  schools (Besides Australian schools) will be 'un-registered'. Each school will  then need to re-register your base which will allow you to register individual  children. To make the registration process quicker, we strongly recommend that  you:</p>
<ol>
  <li><span dir="ltr"> </span>Fill in  the excel sheet with the info of your new children as soon as possible, so you  can upload it right after you register your base.<strong> </strong></li>
  <li><span dir="ltr"> </span>Begin  recruiting your students on the first day of school (Hang up Poster, Watch DVD,  give out Hachayol and registration forms) and make sure all students bring it  in the money by Tuesday, Yud Daled Elul. This way you can register your  children as soon as your base is registered and we can send out the shipment  right away! Please Note: Rank cards will be printed on Thursday and Friday (Tes  Vav - Tes Zayin Elul), any child registered after that date will not receive  their rank card until after Rosh Hashana. <strong> </strong></li>
</ol>
<p><strong>(1) Auction Date - </strong>Children must  choose prizes by auction date. Top 20 auction winners will be announced at the  following rally. You will receive an email with the complete list of winners. <br />
    <strong>For kids who are  graduating program - </strong>Schools  need to make sure that their data entry is done before kids are un-registered (Before  Monday, September 12, midnight) so they will have their miles in the auction. </p>
<p><strong>(2) Data Entry cutoff  date - </strong>Any  data entry done after this time will not be included in this month's rally.  Meaning new promotions or medals earned after this time will be awarded at the  following rally. To generate a report for promotion (pictures) and medals, use  last data entry cutoff date until this data entry cutoff date. </p>
<p><strong>(3)Pick up Date </strong></p>
<p><strong>(4) Shipment once  kids are registered </strong>- Every child registered by Tes Zayin Elul will  receive his things. <strong> </strong></p>
