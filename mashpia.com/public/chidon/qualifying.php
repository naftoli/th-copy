				Each of the three tests has two parts. Each chayol takes both parts of the test.
				<br /><br />
				
				<p class="page-top">
					Part 1: Chidon Qualifying Test - Shabbaton • Plaque • Medal.
				</p>
				
				The Chidon qualifying test is a straightforward yet thorough exam of the information chayolim are responsible to know. It tests the chayol’s <i>memory</i> of the
				Yahadus book’s information, making the Chidon accessible to many.
				<br /><br />
				
				All chayolim who score a combined average of at least 70% or higher on all three Chidon qualifying tests are eligible to join the Shabbaton,
				(depending on each school’s attendance policy).
				<br /><br />
				
				During the Chidon Shabbaton, all chayolim take the Chidon final (this too is a straightforward yet thorough exam on the entire Yahadus book).
				Chayolim who receive at least 70% on the Chidon final will be awarded the Chidon plaque. Chayolim who receive 85% on the Chidon final will be awarded the
				Chidon plaque and the Chidon medal.
				<br /><br />
				
				<p class="page-top">
					Part 2: School representative qualifying test -  Stage • Trophies.
				</p>
				
				The school representative qualifying test assesses how well the material is <i>understood</i> and can be <i>applied</i>. Chayolim must use critical thinking
				to apply the concepts they have learned to new situations.This is the next level in the competition, drawing the most motivated and hardworking chayolim.
				<br /><br />
				
				The highest-scoring chayol of each grade from within each school is eligible to represent their school on stage at the Grand Chidon event
				(depending on each school’s attendance policy).
				<br /><br />
				
				The highest score is determined by the combined mark of all six tests (three Part ones and three Part Twos).
				<br /><br />
				
				In addition to scoring the highest mark, the school representative must receive a 70% average on the three Part One tests and a 70% average on the three Part Two tests.
				<br /><br />
				
				During the Chidon Shabbaton, all school representatives will take a challenging test on the whole Yahadus book, called the “Trophy Final”.
				<br /><br />
				
				The climax of the Chidon is when the Trophy Final winners are announced. The chayolim who earn the highest marks within each grade on the “Trophy Final”
				are awarded the Chidon trophies. First, second, and third place winners will receive beautiful gold, silver, and bronze trophies, respectively.
				<br /><br />
				
				<h4>Tiebreakers</h4>
				Included on each chayol’s third test are “tiebreaker” questions. These questions are only marked in the case of a tie.
				In the case that two chayolim in one grade tie as the highest-scoring in their school, these questions will be marked and taken into account to determine the winner. 
