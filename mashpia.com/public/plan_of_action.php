<h2>PLAN OF ACTION</h2>
<hr />

<h4>How can we make all this a reality?</h4>
<p>
In the beginning Tzivos Hashem, did their best to reach out to as many children as possible; with a newsletter five times a year with one level of yom tov missions for all the children. As the children did those missions each year they climbed in rank and soon become generals.
<br />But we wanted more, after reviewing all the sichos it became clear that the Rebbe wants a real army! But how was this to come to life. It seemed impossible.
<br />Well, we need<br />
1. Tzivos Hashem Bases around the world<br />
2. We need commanders who will train children to be Chayolim – Chassidim, Yirei Shomayim and Lamdonim<br />
3. We need to establish a system of discipline that the children will accept upon themselves.
</p>

<h4>Bases, Commanders, and Soldiers</h4> 
<p>
    Then it became clear that in fact, the Rebbe has an army. We already have mosdos chinuch around the world. Bases established to train children to be Chayolim – Chassidim, Yirei Shomayim and Lamdonim. We have teachers who have dedicated their life to this goal.  We even have the children.    
</p>

<p>
We just have one simple challenge. The schools don’t see themselves as an army base and the teachers don’t see themselves as commanders and the children don’t see themselves as soldiers!
<br />It’s our job to change that reality!
</p>

<h4>System of discipline</h4>
<p>
In which areas of a child life does he need a system of discipline?
<br />The answer is, in everything!  Over the past five years Tzivos Hashem has been working towards that goal.  We started with the areas that were lacking and needed most attention. We have established a seven years system of discipline to run through elementary school.
</p>

<h4>Campaigns</h4>
<p>
    As we started making the system of discipline we realized that just like at school, every subject must be marked with their own grade on a report card. We simply can’t make a system of discipline that will work for all areas of a child life. As we will never be able to monitor in which area the child is doing well and in which area the child will need improvements. So we established campaigns for each area of a child’s life.
<br />Currently they include:<br />
1. Yomei depagra<br />
2. WWTC ‘World Wide Tehillim Club’<br />
3. Mivztoim<br />
4. Yahadus<br />
5. Avos Ubonim<br />
6. Cheshbon Hanefesh<br />
7. Veholachto Bidrochov<br />
8. Niggunim<br />
9. Teffilah<br />
10. Hiskashrus<br />
11. Tanya Baal Peh<br />
12. Chitas<br />
Each campaign has a specific goal. For example the goal of Yomei Depagra is to celebrate!
</p>

<h4>Missions</h4>
<p>
    Each campaign has Missions. For example Yomei Depagra has 90 Missions a year one for each special day on the calendar.  
</p>

<h4>Tasks</h4>
<p>
    Each Mission is made up of tasks. For example each mission for Yomei Depagra will have certain tasks.
<br />Some tasks have a ‘*’ next to them which means that they are mandatory to complete a Mission. Others may be equally important but you don’t need to do them to complete a Mission. Some Missions may have several tasks that have a ‘*’ in that case you need to do all of those tasks to complete a Mission    
</p>

<h4>Medals</h4> 
<p>When a chayol completes a certain amount of Missions they receive a medal. In order to keep motivating the chayol, he can receive up to ten medals for each campaign.
<br />For example, the Yomei Depagra campaign.
<br />When you have completed,
<br />10 Missions = the white Yomei Depagra medal
<br />When you complete another,
<br />15 Missions = the red Yomei Depagra medal
<br />And so on…
<br />You need to complete all your missions for all seven years of elementary to be able to get all ten Yomei Depagra medals.
</p>

<h4>Miles</h4>
<p>
    Chayolim also have the opportunity to receive miles. While mandatory tasks earn the Chayolim medals, all tasks earn them miles. The more miles the more prizes!
</p>

<h4>Mission Sheets – Hachayol Magazine</h4>
<p>
    Each week every chayol gets a personalized mission sheet with all the tasks for all the different campaigns that they took upon themselves to do.
<br />Together with the mission sheet each chayol gets a weekly Hachayol. With the resource material they need to complete the mission. For example, if the mission is to say a sicha, the soldier can find a sicha in the weekly Hachayol to learn.  
<br />Every night the chayolim fill out their mission sheet for what they did that day.  At the end of the week they get their Mission signed and on the first day of a new week the soldiers bring their mission sheets back to school. The school sectary or a Tzivos Hashem volunteer enters what the children have done onto the Tzivos Hashem website.
</p>

<h4>Personalizing mission sheets</h4>
<p>
    No two schools are the same and no two children are the same. As they say, “one size does not fit anyone.”  We have made the system flexible that each school, class, or child can choose which campaigns and task they would like to appear on their mission sheet and when. They are also able to personalize their own tasks to be added to the mission sheet.       
<br />In addition, there are also different tasks for children who are in Chabad day schools.   
</p>

<h4>Keeping track</h4>
<p>
    Each Chayol gets a binder with dividers for each campaign.
<br />Each campaign has a set of sticker boards. (One sticker board for each medal, ten medals per campaign)
<br />Each week the chayolim get a sheet of stickers for each Mission completed to be placed on their sticker board.
<br />When they have completed a sticker board they earn that medal and can now move on to the next sticker board.  
<br />Updated sticker board binders - giving the chayolim clear goals from the get go.
<br />Every NEW child who joins Tzivos Hashem will receive a leather style green binder with the 12 dividers (one for each campaign) that clearly state the goal and tasks of each campaign, together with 84 sticker boards. There are seven sticker boards for each campaign - white - purple). By completing this binder they will become a 3 star general. 
.</p>

<h4>Sticker Book</h4>
<p>Every year the Chayolim receive a sticker book with separate sticker sheets for each week. The stickers are only for the mandatory missions.  As the chayolim complete their missions they can place the appropriate sticker of their sticker boards to help them keep track. More stickers = more MEDALS!
<br />Our feedback from all the schools that have used the stickers properly had the older children in the school (seventh or eighth grade) review the missions sheets with the younger students and give them the stickers they earned. Or in some schools, the older students mark the mission sheets and staple a sticker sheet for that week to the mission sheet. Then they return it to the chayolim to place the stickers on their sticker board in their binder. 
</p>
