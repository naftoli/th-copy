    <strong> </strong>
    Cheshbon Hanefesh <strong></strong>
</p>
<p>
    <strong>Goal:</strong>
    To go to sleep and wake up as a true Chayol, and complete the mission checklist, think upon how the day went and how to make tomorrow better.
</p>
<p>
    <strong>Soldier's Tasks: </strong>
</p>
<p>
    <strong>Waking up as a chayol</strong>
    <strong></strong>
</p>
<p>
    &#183; As soon as they wake up, recognize that the king that creates and gives life to the world is standing before them. HE has given them their life,
their neshoma, because HE trusts in them to serve him properly. By putting their hands together, lowering their head and saying Modeh Ani out loud.    <strong></strong>
</p>
<p>
    &#183; Wash Negel Vasser by their beds without putting their feet on the ground and emptying the Tomei Negel Vasser.
</p>
<p>
    &#183; Getting dressed in a tzniusdik way under their covers, to remember that Hashem is standing before us.
</p>
<ul>
    <li>
        Washing 2<sup>nd</sup> Negel Vasser and saying the brocha <em>Al Netilas Yodayim</em>, with their hands held apart by their payos/ears.
    </li>
    <li>
        Brush their teeth
    </li>
</ul>
<p>
    &#183; Eat Breakfast, make the proper brochos before and after, and clean up.
</p>
<ul>
    <li>
        Say Brias Shema Bizman.
    </li>
</ul>
<p>
    <strong>Going to sleep as a chayol</strong>
</p>
<p>
    &#183; Make the proper brochos before and after supper and clean up after themselves<strong></strong>
</p>
<ul>
    <li>
        Prepare Negel Vasser by their beds<strong></strong>
    </li>
</ul>
<p>
    &#183; Say Krias Shema from a siddur in their Cheder Tzivos Hashem<strong></strong>
