                          <h1><span style="font-size: 22px; color: #4D0C0D;">About Rabbi Sholem Perl</span></h1>
                            
                        </h2>
                        <p> Rabbi Sholem Perl has been a master Rebbi and storyteller for 35 years. He is now recording stories of Tzadikim of yesteryear with theatrical drama, music and sound effects, which are both suspenseful and adventurous. Rabbi Sholem Perl captivates the imagination of children of all ages with stories that portray Torah values, Yiras Shomayim, Emunas Tzaddikim and Good Middos, which are based on the teachings of the Chazal and our Rebbeim. </p>
<p>
These stories will affect the hearts and minds of todays youth. They will address the emotional, social and traditional challenges that are facing our youth today.</p>
<p>
The values his stories will instill:
responsibility, pride in our Jewish heritage, tolerance, self-esteem, patients, appreciation, love and generosity, truthfulness and sensitivity, justice and mercy, consideration and respect, courage, accountability, honesty, meaning and purpose of life.
</p>

<p>Rabbi Perl, originally from London, is married to his wife Leah, and is blessed with children and grandchildren, Kein Yirbu.</p>
<p>
Rabbi Sholem Perl began his educational career in 1978 in New York as a Director of the Youth Programs for the newly arrived Iranian immigrant teens. Upon seeing his success with the youth, in 1980 Rabbi Perl was hired as a guide and educator to teach Talmudical and Judaic Studies at the United Lubavitcher Yeshiva, in Brooklyn NY. He succeeded in imbuing his students with a true love for learning and Hiskashrus to the Rebbe, Nosi Doreinu.</p>
<p>
In 1982 Rabbi Perl and his family were transferred by Yeshivah Ohr Elchonon Chabad of Los Angeles, CA where he taught Talmudical Studies, as well as various Judaic subjects. There, he had a tremendous impact on many students over the eleven year period. Many of Rabbi Perl’s students affectionately mention that the year they had spent with him in class will always be ingrained in their memory.</p>
<p>
In 1993-2001 Rabbi Perl became the Director of Outreach at the Chabad Russian Immigrant Program in Los Angeles. He helped develop programs for over five thousand Russian immigrant children.  In 2002 Rabbi Perl realized the tremendous need for a Jewish trade school for teens. He is now the Director of Outreach at JETS, The Jewish Educational Trade School in Granada Hills, CA.
</p>


