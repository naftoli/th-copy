                        <h4>Mitzvah Names</h4>
                        Chayolim must be familiar with the names of the mitzvos in Hebrew. They do not need to know the names of mitzvos by heart, but they do need to be able to recognize them.
                        <br /><br />
                        All tests and quizzes will refer to the names of the mitzvos in Hebrew. Mitzvah names will not be translated.
                        <br /><br />
                        If two or mitzvos are grouped together in a mitzva box, then you are only required to know the name of the individual mitzva
                        (if the individual mitzva name is not listed in the book see that unit in the Book Changes section of this guide); not the general heading at the top of the mitzva box.
                        <br /><br />
                        
                        <h4>Translation of Mitzvah Names</h4>
                        Chayolim must know the English translation of the mitzvah names—the words directly beneath the name in Hebrew.
                        <br /><br />
                        If two or mitzvos are grouped together in a mitzva box, then you are only required to know the translation of the individual mitzva listed in the individual rows of the
                        mitzva box; not the translation of the general heading at the top of the mitzva box.
                        <br /><br />
                        
                        <h4>Recognizing the Makor</h4>
                        Only Grades 7 and 8 are responsible for this information. They do not need to know the source pesukim by heart, but will need to recognize the relevant part of the posuk
                        (only the words in bold) and connect it back to the mitzva. (For example: What mitzvah do we learn from the source “Anochi Hashem Elokecha?”) 
                        <br /><br />
                        
                        <h4>Synopsis of the Mitzvah</h4>
                        Chayolim must know the synopsis of the mitzvah—the words directly above the icons.
                        <br /><br />
                        
                        <h4>Icons</h4>
                        <i>To whom it applies; Where it applies; When it applies; Punishments</i><br /><br />
                        Students must know the icons for each mitzvah. The icons are the circles at the end or the side of the mitzvah boxes with the information of to whom, where, and
                        when the mitzvah applies, as well as the applicable punishment for transgressing the mitzvah.
                        <br /><br />
                        
                        Chayolim need to be very familiar with each mitzvah on its own, as there will be many questions asking about these details. Chayolim need to train themselves to
                        identify each mitzvah individually and not <i>only</i> as part of a unit. 
                        <br /><br />
                        
                        <h4>Relevant terms</h4>
                        Chayolim <i>must</i> know all Hebrew terms and concepts that appear in the sections of the book that they are responsible for. To help with translations,
                        Tzivos Hashem has put together a glossary of Hebrew terms for each book, found in the Chidon Learning Guide. However, <span style="font-weight: bold;">the glossary does not list all the words that the
                        Chayolim are responsible to know.</span> Chayolim are responsible to make sure they know and understand all Hebrew terms and concepts—including those not listed in the glossary.
                        <br /><br />
                        
                        <h4>Details</h4>
                        Chayolim must know all the details of each unit (except for those sections listed in the Book Changes section of the Chidon study guide for books 2, 3, and 4).
                        <br /><br />
                        Chayolim should pay special attention to which details apply to which mitzva, because mitzvos are grouped together in units, and it can be hard to identify
                        which details are for which mitzva.
